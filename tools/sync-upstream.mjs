#!/usr/bin/env node
/**
 * Vendor the upstream reverse-skill corpus into this package.
 *
 * The upstream repository is the single source of truth for everything under
 * the vendored trees. This script mirrors it, prunes files upstream deleted,
 * and records the exact upstream commit plus a per-file digest so drift is
 * detectable in CI.
 *
 * Usage:
 *   node tools/sync-upstream.mjs                 # mirror upstream, write files
 *   node tools/sync-upstream.mjs --check         # report drift, write nothing
 *   node tools/sync-upstream.mjs --no-bump       # do not bump the patch version
 *   node tools/sync-upstream.mjs --upstream DIR  # use a local clone instead
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import {
  copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync,
  rmSync, statSync, writeFileSync
} from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_ROOT = fileURLToPath(new URL('..', import.meta.url));
const DEFAULT_REPO = 'https://github.com/zhaoxuya520/reverse-skill.git';
const DEFAULT_BRANCH = 'main';
const CACHE_DIR = join(PACKAGE_ROOT, '.sync-cache', 'upstream');
const MANIFEST_FILE = join(PACKAGE_ROOT, 'tools', 'upstream-files.json');
const UPSTREAM_FILE = join(PACKAGE_ROOT, 'upstream.json');

/** Top-level upstream directories mirrored into this package. */
const MIRRORED_DIRECTORIES = [
  'skills',
  'CTF-Sandbox-Orchestrator',
  'docs',
  'examples',
  'kali',
  'scripts',
  'burp-mcp-full',
  'reports'
];

/** Top-level upstream files mirrored verbatim. */
const MIRRORED_FILES = [
  '.gitattributes',
  'RULES.md',
  'RULES_zh.md',
  'SECURITY.md',
  'CHANGELOG.md',
  'AGENTS.md',
  'CLAUDE.md',
  'VERSION',
  'reverse-skill.png'
];

/** Upstream files mirrored under a different destination name. */
const RENAMED_FILES = {
  'LICENSE': 'UPSTREAM-LICENSE',
  'README.md': 'UPSTREAM-README.md',
  'README_zh.md': 'UPSTREAM-README_zh.md',
  'README_AI.md': 'UPSTREAM-README_AI.md',
  'README-kali.md': 'UPSTREAM-README-kali.md'
};

/**
 * Upstream paths that are deliberately not vendored:
 *   .git, .github  repository plumbing rather than content
 *   plugins/       Codex adapter whose router duplicates skills/SKILL.md
 *   work, mcps     local run artifacts
 *   tool-index.*   machine specific, regenerated by the upstream scripts
 */
const EXCLUDED_PATHS = new Set([
  '.git',
  '.github',
  'plugins',
  'work',
  'mcps',
  'node_modules',
  'implementation-notes.md',
  'BOOTSTRAP.md',
  'LOCAL-READINESS.md',
  'skills/tool-index.md',
  'skills/tool-index.json'
]);

const toPosix = (value) => value.split(sep).join('/');
const sha256 = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');
const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'));

/** Whether an upstream-relative posix path is vendored. */
function isVendored(relPosix) {
  if (EXCLUDED_PATHS.has(relPosix)) return false;
  for (const excluded of EXCLUDED_PATHS) {
    if (relPosix.startsWith(excluded + '/')) return false;
  }
  if (relPosix.indexOf('__pycache__') !== -1) return false;
  if (relPosix.endsWith('.keystore') || relPosix.endsWith('.pyc')) return false;
  return true;
}

/** Recursively list files below a directory. */
function walk(directory) {
  const files = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const full = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else if (entry.isFile()) files.push(full);
  }
  return files;
}

/**
 * Enumerate the upstream checkout.
 * Returns a Map of package-relative posix path -> absolute source path.
 */
function planMirror(upstreamRoot) {
  const plan = new Map();
  for (const name of MIRRORED_FILES) {
    const source = join(upstreamRoot, name);
    if (existsSync(source) && statSync(source).isFile()) plan.set(name, source);
  }
  for (const [name, destination] of Object.entries(RENAMED_FILES)) {
    const source = join(upstreamRoot, name);
    if (existsSync(source) && statSync(source).isFile()) plan.set(destination, source);
  }
  for (const directory of MIRRORED_DIRECTORIES) {
    const source = join(upstreamRoot, directory);
    if (!existsSync(source) || !statSync(source).isDirectory()) continue;
    for (const file of walk(source)) {
      const relPosix = toPosix(relative(upstreamRoot, file));
      if (!isVendored(relPosix)) continue;
      plan.set(relPosix, file);
    }
  }
  return plan;
}

/** Clone or refresh the upstream checkout used as the sync source. */
function ensureUpstream(repo, branch) {
  const git = (args, cwd) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  if (!existsSync(join(CACHE_DIR, '.git'))) {
    rmSync(CACHE_DIR, { recursive: true, force: true });
    mkdirSync(dirname(CACHE_DIR), { recursive: true });
    git(['clone', '--depth', '1', '--branch', branch, repo, CACHE_DIR], PACKAGE_ROOT);
  } else {
    git(['fetch', '--depth', '1', 'origin', branch], CACHE_DIR);
    git(['reset', '--hard', 'FETCH_HEAD'], CACHE_DIR);
    git(['clean', '-fdx'], CACHE_DIR);
  }
  return CACHE_DIR;
}

function gitOutput(directory, args) {
  return execFileSync('git', args, { cwd: directory, encoding: 'utf8' }).trim();
}

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const bump = !argv.includes('--no-bump');
const localIndex = argv.indexOf('--upstream');
const repoIndex = argv.indexOf('--repo');
const repo = repoIndex >= 0 ? argv[repoIndex + 1] : DEFAULT_REPO;
const branch = DEFAULT_BRANCH;

const upstreamRoot = localIndex >= 0 ? resolve(argv[localIndex + 1]) : ensureUpstream(repo, branch);
const commit = gitOutput(upstreamRoot, ['rev-parse', 'HEAD']);
const commitDate = gitOutput(upstreamRoot, ['log', '-1', '--format=%cI']);
const upstreamVersion = existsSync(join(upstreamRoot, 'VERSION'))
  ? readFileSync(join(upstreamRoot, 'VERSION'), 'utf8').trim()
  : 'unknown';

const plan = planMirror(upstreamRoot);
const next = {};
for (const [destination, source] of plan) next[destination] = sha256(source);

const previousManifest = existsSync(MANIFEST_FILE) ? readJson(MANIFEST_FILE) : { files: {} };
const previous = previousManifest.files || {};

const added = Object.keys(next).filter((key) => previous[key] === undefined).sort();
const removed = Object.keys(previous).filter((key) => next[key] === undefined).sort();
const changed = Object.keys(next)
  .filter((key) => previous[key] !== undefined && previous[key] !== next[key])
  .sort();

const summary = {
  upstream: repo,
  commit,
  commitDate,
  upstreamVersion,
  vendoredFiles: Object.keys(next).length,
  added: added.length,
  removed: removed.length,
  changed: changed.length,
  sampleAdded: added.slice(0, 10),
  sampleRemoved: removed.slice(0, 10),
  sampleChanged: changed.slice(0, 10)
};

if (check) {
  const upToDate = added.length === 0 && removed.length === 0 && changed.length === 0;
  console.log(JSON.stringify({ ...summary, upToDate }, null, 2));
  process.exitCode = upToDate ? 0 : 1;
} else {
  for (const [destination, source] of plan) {
    const target = join(PACKAGE_ROOT, destination);
    mkdirSync(dirname(target), { recursive: true });
    copyFileSync(source, target);
  }
  for (const key of removed) rmSync(join(PACKAGE_ROOT, key), { force: true });

  writeFileSync(MANIFEST_FILE, JSON.stringify({ upstream: repo, commit, commitDate, files: next }, null, 2) + String.fromCharCode(10));
  writeFileSync(UPSTREAM_FILE, JSON.stringify({
    repository: repo,
    branch,
    commit,
    commitDate,
    upstreamVersion,
    syncedAt: new Date().toISOString(),
    vendoredFiles: Object.keys(next).length,
    excluded: [...EXCLUDED_PATHS].sort()
  }, null, 2) + String.fromCharCode(10));

  const manifestPath = join(PACKAGE_ROOT, 'package.json');
  const pkg = readJson(manifestPath);
  const contentChanged = added.length + removed.length + changed.length > 0;
  if (bump && contentChanged) {
    const parts = pkg.version.split('.').map((part) => Number.parseInt(part, 10));
    pkg.version = parts[0] + '.' + parts[1] + '.' + (parts[2] + 1);
  }
  pkg.upstreamCommit = commit;
  writeFileSync(manifestPath, JSON.stringify(pkg, null, 2) + String.fromCharCode(10));
  console.log(JSON.stringify({ ...summary, contentChanged, version: pkg.version }, null, 2));
}
